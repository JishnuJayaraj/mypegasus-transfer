import { AccessCategory } from "../fields/catalog";
import { decideAccess, type AccessAction, type AccessPhase, type Decision } from "./decide";
import { accessModes, accessProfiles, sampleResource } from "./profiles";

const actions: AccessAction[] = ["read", "list", "open_document", "write"];
const phases: AccessPhase[] = ["active", "evidence_set"];
const modes = Object.keys(accessModes) as (keyof typeof accessModes)[];
const questions = {
  Q65: "write permissions, pending the DPO and PL review",
  Q87: "audit metadata beyond the regional operations manager, documents other than the signed forms, writes in the evidence set",
};

const code = (value: string) => `\`${value}\``;
const table = (head: string[], rows: string[][]) =>
  [head, head.map(() => "---"), ...rows].map((r) => `| ${r.join(" | ")} |`).join("\n");

function text(d: Decision): string {
  if (d.effect === "deny") return d.question ? `no: undecided (${d.question})` : `no: ${d.because}`;
  const view = d.view === "full" ? "yes" : d.view;
  return [view, d.audit, d.grant && "grant", d.flagForReview && "review"]
    .filter(Boolean)
    .join(" · ");
}

type Cell = {
  label: string;
  staff: boolean;
  category: AccessCategory;
  action: AccessAction;
  decision: Decision;
};

function cells(phase: AccessPhase, mode: keyof typeof accessModes): Cell[] {
  return accessProfiles.flatMap(({ label, subject }) =>
    AccessCategory.options.flatMap((category) =>
      actions.map((action) => {
        const resource = sampleResource(category, phase);
        return {
          label,
          staff: subject.kind === "staff",
          category,
          action,
          decision: decideAccess(subject, resource, action, accessModes[mode]),
        };
      }),
    ),
  );
}

function section(phase: AccessPhase, mode: keyof typeof accessModes): string {
  const heading = `## ${phase === "active" ? "Active" : "Evidence-set"} phase, ${mode.replace("_", "-")} mode`;
  const current = cells(phase, mode);
  if (mode === "normal") {
    const rows = [];
    for (let i = 0; i < current.length; i += actions.length) {
      const row = current.slice(i, i + actions.length);
      rows.push([row[0]!.label, code(row[0]!.category), ...row.map((c) => text(c.decision))]);
    }
    return `${heading}\n\n${table(["Subject", "Category", ...actions.map(code)], rows)}`;
  }
  const normal = cells(phase, "normal");
  const changed = current
    .map((c, i) => [c, text(normal[i]!.decision), text(c.decision)] as const)
    .filter(([c, before, after]) => c.staff && before !== after)
    .map(([c, before, after]) => [c.label, code(c.category), code(c.action), before, after]);
  const body = changed.length
    ? table(["Subject", "Category", "Action", "Normal mode", "This mode"], changed)
    : "No cell differs from normal mode.";
  return `${heading}\n\nOnly the staff cells that differ from normal mode.\n\n${body}`;
}

function undecided(): string {
  const rows = new Map<string, string[]>();
  for (const phase of phases) {
    for (const mode of modes) {
      for (const c of cells(phase, mode)) {
        if (c.decision.effect !== "deny" || !c.decision.question) continue;
        const key = [c.decision.question, c.label, code(c.category), code(c.action)].join(" | ");
        rows.set(key, [...(rows.get(key) ?? []), `${phase} ${mode}`]);
      }
    }
  }
  return table(
    ["Question", "Subject", "Category", "Action", "Phase and mode"],
    [...rows]
      .toSorted(([a], [b]) => a.slice(0, 3).localeCompare(b.slice(0, 3)))
      .map(([key, where]) => {
        const all = where.length === phases.length * modes.length;
        return [...key.split(" | "), all ? "all" : where.join(", ")];
      }),
  );
}

/** docs/domain/generated/access-matrix.md, written by `pnpm generate`. */
export function renderAccessMatrixDoc(): string {
  const sections = phases.flatMap((phase) => modes.map((mode) => section(phase, mode)));
  return `# Access matrix (generated)

Generated by \`pnpm generate\` from \`packages/domain/src/access\`. Do not edit: CI fails when
this file differs from the code. The rules behind it are in
[data-protection.md](../data-protection.md) and the Slice 1 plan, section 5.6; they are
*assumed* (Q28, Q49, Q51, Q61–Q65, Q80) until the DPO confirms them (pre-pilot gate).

How to read it: one row per subject and category, one column per action, for one participation
of the subject's project and region. \`yes\` is the full view; \`sensitive_read\`,
\`sensitive_write\`, \`document_opened\` and \`break_glass_access\` name the audit entry; a
break-glass \`grant\` covers that one participant, category and action and is flagged for
\`review\`. Participant writes are shown for a self-service field of the category; their other
fields are \`never\`. Not shown: staff without a role in the project are \`not_member\`, org roles
outside their region \`out_of_region\`; participants reach only their own participation and
have no modes (every other mode is \`never\` for them). Unknown access is denied: \`undecided\` names the open question (D10).

${sections.join("\n\n")}

## Undecided cells

${Object.entries(questions)
  .map(([q, topic]) => `- **${q}**: ${topic} ([open-questions.md](../../open-questions.md)).`)
  .join("\n")}

${undecided()}
`;
}
