import { writeFileSync } from "node:fs";
import { openApiDocument } from "@transfer/api";
import openapiTS, { astToString } from "openapi-typescript";

// `pnpm api:generate`: writes openapi.json and src/schema.d.ts. Both are committed, and CI
// fails when they differ from what the API generates (ADR-0010).
const doc = openApiDocument();
const json = `${JSON.stringify(doc, null, 2)}\n`;
const ast = await openapiTS(json);
const header = "// Generated by `pnpm api:generate` from openapi.json. Do not edit.\n\n";

writeFileSync(new URL("../openapi.json", import.meta.url), json);
writeFileSync(new URL("../src/schema.d.ts", import.meta.url), header + astToString(ast));
