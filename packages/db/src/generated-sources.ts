import { reservedEventTypes } from "@transfer/domain";
import { readFileSync } from "node:fs";
import { join } from "node:path";
import { erasureDeletionTables, evidenceOnlyTables } from "./data-catalog";
import { sourcesFolder } from "./function-sources";

/**
 * The inventories the generated function sources hold (ADR-0002, generated lists). Only
 * membership, and for the erasure the hand-written order of the catalog: no rule is generated.
 */
export interface GeneratedLists {
  /** The event types `record_audit_event` refuses: the domain's `reservedEventTypes`. */
  reservedEventTypes: readonly string[];
  /** The tables `retention_erase_participation` deletes from, in the catalog's erasure order. */
  erasureTables: readonly string[];
  /** The tables carrying the evidence-only trigger. */
  evidenceOnlyTables: readonly string[];
}

export const generatedLists = (): GeneratedLists => ({
  reservedEventTypes: [...reservedEventTypes],
  erasureTables: erasureDeletionTables(),
  evidenceOnlyTables: evidenceOnlyTables(),
});

const generator = "packages/db/src/scripts/generate-sources.ts";

/** A generated function: its hand-written template and the list that fills the placeholder. */
const functionSources: {
  source: string;
  template: string;
  placeholder: string;
  from: string;
  list: (lists: GeneratedLists) => readonly string[];
}[] = [
  {
    source: "functions/audit/record_audit_event.sql",
    template: "templates/record_audit_event.sql",
    placeholder: "/*generated:reserved_event_types*/",
    from: "reservedEventTypes (packages/domain/src/audit/events.ts)",
    list: (lists) => lists.reservedEventTypes,
  },
  {
    source: "functions/retention/retention_erase_participation.sql",
    template: "templates/retention_erase_participation.sql",
    placeholder: "/*generated:erasure_tables*/",
    from: "erasureParticipationTables (packages/db/src/data-catalog.ts)",
    list: (lists) => lists.erasureTables,
  },
];

const evidenceOnlySource = "triggers/generated/evidence_set_phase.sql";

/** Every generated source, relative to the sources folder. */
export const generatedSources: readonly string[] = [
  ...functionSources.map((entry) => entry.source),
  evidenceOnlySource,
];

const identifier = /^[a-z][a-z0-9_]{0,62}$/;

/** The names as quoted SQL literals, wrapped at 100 columns, each line at `indent`. */
function literals(names: readonly string[], indent: string): string {
  const lines: string[] = [];
  let line = indent;
  names.forEach((name, i) => {
    if (!identifier.test(name)) throw new Error(`generated sources: ${name} is not an identifier`);
    const item = `'${name}'${i < names.length - 1 ? "," : ""}`;
    if (line !== indent && line.length + 1 + item.length > 100) {
      lines.push(line);
      line = indent;
    }
    line += line === indent ? item : ` ${item}`;
  });
  lines.push(line);
  return lines.join("\n");
}

const header = (from: string, edit: string) =>
  `-- Generated by ${generator} (pnpm generate) from ${from}.\n-- Do not edit: ${edit}\n`;

/**
 * The content of every generated source: a function is its template in `sql/templates` with the
 * list in place of the placeholder's line; the evidence-only triggers are one statement per table.
 */
export function renderGeneratedSources(
  lists: GeneratedLists = generatedLists(),
  folder = sourcesFolder,
): Record<string, string> {
  const rendered: Record<string, string> = {};
  for (const entry of functionSources) {
    const template = readFileSync(join(folder, entry.template), "utf8");
    const lines = template.split("\n");
    const at = lines.findIndex((line) => line.trim() === entry.placeholder);
    if (at < 0 || template.split(entry.placeholder).length !== 2) {
      throw new Error(
        `generated sources: ${entry.template} needs ${entry.placeholder} once, alone on its line`,
      );
    }
    const names = entry.list(lists);
    if (names.length === 0 || new Set(names).size !== names.length) {
      throw new Error(`generated sources: the list of ${entry.source} is empty or repeats a name`);
    }
    lines[at] = literals(names, lines[at]!.slice(0, lines[at]!.indexOf(entry.placeholder)));
    rendered[entry.source] =
      header(
        `sql/${entry.template} and ${entry.from}`,
        "change the function in its template, the list in the model.",
      ) + lines.join("\n");
  }
  const tables = lists.evidenceOnlyTables.toSorted();
  if (tables.length === 0 || new Set(tables).size !== tables.length) {
    throw new Error(`generated sources: the list of ${evidenceOnlySource} is empty or repeats`);
  }
  rendered[evidenceOnlySource] =
    header(
      "erasureParticipationTables and evidenceOnlyExemptTables (packages/db/src/data-catalog.ts)",
      "a table gets or loses the trigger in the data catalog.",
    ) +
    tables
      .map((table) => {
        if (!identifier.test(table)) {
          throw new Error(`generated sources: ${table} is not an identifier`);
        }
        return `CREATE OR REPLACE TRIGGER ${table}_evidence_set_phase BEFORE INSERT OR DELETE OR UPDATE ON public.${table} FOR EACH ROW EXECUTE FUNCTION public.refuse_in_evidence_set_phase();\n`;
      })
      .join("");
  return rendered;
}

/** The generated sources whose file differs from what the generator writes now. */
export function staleGeneratedSources(
  lists: GeneratedLists = generatedLists(),
  folder = sourcesFolder,
): string[] {
  return Object.entries(renderGeneratedSources(lists, folder))
    .filter(([name, content]) => {
      try {
        return readFileSync(join(folder, name), "utf8") !== content;
      } catch {
        return true;
      }
    })
    .map(([name]) => name);
}
